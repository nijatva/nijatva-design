#!/usr/bin/env python3
"""Generate Android colour and dimension resources from tokens/tokens.json.

Usage:
    python3 scripts/gen_tokens.py            # writes generated/
    python3 scripts/gen_tokens.py --check    # exits 1 if generated/ is stale

Generated files are committed. Hand-editing them is a bug: change tokens.json.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "tokens" / "tokens.json"
OUT = ROOT / "generated"

HEADER = "<!-- Generated by scripts/gen_tokens.py from tokens/tokens.json. Do not edit. -->\n"


def camel(name: str) -> str:
    """bg -> bg, surfaceAlt -> surface_alt, accentDeep -> accent_deep (Android style)."""
    out = []
    for ch in name:
        if ch.isupper():
            out.append("_")
        out.append(ch.lower())
    return "".join(out)


def colors_xml(tokens: dict, theme: str) -> str:
    lines = ['<?xml version="1.0" encoding="utf-8"?>', HEADER.strip(), "<resources>"]
    for name, value in tokens["color"].items():
        lines.append(f'    <color name="nj_{camel(name)}">{value[theme]}</color>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def dimens_xml(tokens: dict) -> str:
    lines = ['<?xml version="1.0" encoding="utf-8"?>', HEADER.strip(), "<resources>"]
    for name, dp in tokens["spacing"].items():
        lines.append(f'    <dimen name="nj_space_{name}">{dp}dp</dimen>')
    for name, dp in tokens["radius"].items():
        unit = "dp" if dp < 999 else "dp"
        lines.append(f'    <dimen name="nj_radius_{name}">{dp}{unit}</dimen>')
    for name, t in tokens["type"].items():
        lines.append(f'    <dimen name="nj_text_{name}">{t["size"]}sp</dimen>')
        lines.append(f'    <dimen name="nj_line_{name}">{t["lineHeight"]}sp</dimen>')
    lines.append(f'    <dimen name="nj_touch_min">{tokens["touchTargetMinDp"]}dp</dimen>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def build() -> dict:
    tokens = json.loads(TOKENS.read_text())
    return {
        OUT / "values" / "colors.xml": colors_xml(tokens, "dark"),
        OUT / "values-night" / "colors.xml": colors_xml(tokens, "amoled"),
        OUT / "values" / "dimens.xml": dimens_xml(tokens),
    }


def main() -> int:
    files = build()
    if "--check" in sys.argv:
        stale = [p for p, body in files.items() if not p.exists() or p.read_text() != body]
        if stale:
            print("stale, run scripts/gen_tokens.py:", ", ".join(str(p) for p in stale))
            return 1
        print("tokens up to date")
        return 0
    for path, body in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
        print("wrote", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
